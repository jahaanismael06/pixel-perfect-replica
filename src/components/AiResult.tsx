import { useState } from "react";
import { Copy, RefreshCw, Trash2, Sparkles, Loader2, Check } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { generateAI } from "@/lib/ai.functions";

export type Feature = "email" | "meeting" | "planner";

export function useAi(feature: Feature) {
  const [text, setText] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const run = async (prompt: string) => {
    setLoading(true); setError(null);
    try {
      const r = await generateAI({ data: { feature, prompt } });
      if (r.ok) setText(r.text); else setError(r.error);
    } catch {
      setError("Could not reach the AI. Please try again.");
    } finally { setLoading(false); }
  };
  return { text, setText, loading, error, run, clear: () => { setText(""); setError(null); } };
}

export function PageHeader({ title, subtitle }: { title: string; subtitle: string }) {
  return (
    <div className="mb-6">
      <h1 className="font-display text-3xl md:text-4xl">{title}</h1>
      <p className="mt-1 text-muted-foreground">{subtitle}</p>
    </div>
  );
}

export function AiResult({ ai, onRegenerate, emptyHint }: {
  ai: ReturnType<typeof useAi>; onRegenerate: () => void; emptyHint: string;
}) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    await navigator.clipboard.writeText(ai.text);
    setCopied(true); setTimeout(() => setCopied(false), 1500);
  };
  return (
    <section aria-live="polite" className="flex min-h-[420px] flex-col rounded-3xl border bg-card p-5 shadow-soft">
      <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
        <h2 className="font-display text-xl">Result</h2>
        <div className="flex gap-1">
          <Button size="sm" variant="ghost" onClick={copy} disabled={!ai.text || ai.loading}>
            {copied ? <Check /> : <Copy />} {copied ? "Copied" : "Copy"}
          </Button>
          <Button size="sm" variant="ghost" onClick={onRegenerate} disabled={!ai.text || ai.loading}>
            <RefreshCw /> Regenerate
          </Button>
          <Button size="sm" variant="ghost" onClick={ai.clear} disabled={(!ai.text && !ai.error) || ai.loading}>
            <Trash2 /> Clear
          </Button>
        </div>
      </div>
      {ai.error && <p role="alert" className="mb-3 rounded-xl bg-destructive/10 p-3 text-sm text-destructive">{ai.error}</p>}
      {ai.loading ? (
        <div className="flex flex-1 flex-col items-center justify-center gap-3 text-muted-foreground">
          <Loader2 className="size-6 animate-spin text-primary" /> Bloom is thinking…
        </div>
      ) : ai.text ? (
        <Textarea aria-label="Editable result" value={ai.text} onChange={(e) => ai.setText(e.target.value)}
          className="flex-1 resize-none rounded-2xl bg-cream/40 font-sans text-sm leading-relaxed md:text-sm" />
      ) : (
        <div className="flex flex-1 flex-col items-center justify-center gap-3 rounded-2xl bg-bloom p-6 text-center text-muted-foreground">
          <Sparkles className="size-6 text-primary" /> {emptyHint}
        </div>
      )}
      <p className="mt-3 text-xs text-muted-foreground">Generated by AI — review and edit before sending or sharing.</p>
    </section>
  );
}
